def case_by_id(case_id: str) -> GoldenCase:
    """按 id 取夹具，跑单个用例时用"""
    for case in CASES:
        if case.id == case_id:
            return case
    raise KeyError(f"没有 id={case_id} 的夹具，现有：{', '.join(c.id for c in CASES)}")
